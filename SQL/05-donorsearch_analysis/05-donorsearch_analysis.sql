-- 5_Исследовать вовлечение новых доноров через социальные сети. 
--   Узнать, сколько по каким каналам пришло доноров.
--   среднее количество донаций по каждому каналу.
select case  
       	   WHEN autho_vk THEN 'ВКонтакте'
           WHEN autho_ok THEN 'Одноклассники'
           WHEN autho_tg THEN 'Telegram'
           WHEN autho_yandex THEN 'Яндекс'
           WHEN autho_google THEN 'Google'
           ELSE 'Без авторизации через соцсети'
           END AS social_network,
      count(id) as users,
      round(avg(confirmed_donations),2) as conf_donations
from donorsearch.user_anon_data
group by social_network
order by conf_donations desc

