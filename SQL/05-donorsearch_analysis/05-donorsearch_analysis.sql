--4_Оценка, как система бонусов влияет на зарегистрированные в системе донации.
-- Определим кто доноры у которых подтверденые зарегистрированые донации
with active_users as(
select ud.id , ud.confirmed_donations,
      coalesce(ua.user_bonus_count,0) as user_bonus_count
from donorsearch.user_anon_data as ud
left join donorsearch.user_anon_bonus as ua on ud.id = ua.user_id)
select case
	      when user_bonus_count > 0
	      then 'Получили бонусы'
	      else 'Не получили бонусы'
          end as status_bonus,
       count(id) as count_doners,
       round(avg(confirmed_donations),2) as avg_donations
from active_users 
group by status_bonus
order by count_doners 
--|status_bonus      |count_doners|avg_donations|
