--2_Динамику общего количества донаций в месяц за 2022 и 2023 годы.
-- 1.CTE общая таблица с динамикой по месяцам и годам с относительным отклонением и абсолютным.
with main_table as (
select *, (select c_don_2023 - c_don_2022) as difference, 
                  round(((w.c_don_2023::numeric/q.c_don_2022::numeric)- 1) * 100, 2) as percent
from (select extract(year from donation_date::timestamp) as year_2022,
             extract(month from donation_date::timestamp) as month_2022,
             COUNT(id) as c_don_2022        
             from donorsearch.donation_anon
             where extract(year from donation_date::timestamp) = '2022'   
             group by year_2022, month_2022) as q 
left join (select extract(year from donation_date::timestamp) as year_2023,
                  extract(month from donation_date::timestamp) as month_2023,
                  COUNT(id) as c_don_2023         
                  from donorsearch.donation_anon
                  where extract(year from donation_date::timestamp) = '2023'     
                  group by year_2023, month_2023) as w on q.month_2022 = w.month_2023),
-- Создание СТE с итоговыми значениями таблицы main_table
last_table as (
select avg(year_2022) as year_2022, count(month_2022) as month_2022, sum(c_don_2022) as c_don_2022,
       avg(year_2023) as year_2023, count(month_2023) as month_2023, sum(c_don_2023) as c_don_2023,
       sum(c_don_2023) - sum(c_don_2022) as difference,
       round(((sum(c_don_2023)::numeric/sum(c_don_2022)::numeric)- 1) * 100, 2) as percent       
from main_table)
-- Соединение таблиц 
select *
from last_table 
union all
select *
from main_table
